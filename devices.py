def get_device_by_model(model_name: str) -> Optional[Dict[str, Any]]:
    """Look up a device template by model name or marketing name (case-insensitive)."""
    query = model_name.strip().lower()
    for d in REAL_ANDROID_DEVICES:
        if d["model"].lower() == query or d.get("marketing_name", "").lower() == query:
            return dict(d)
    # Substring search fallback
    for d in REAL_ANDROID_DEVICES:
        if query in d["model"].lower() or query in d.get("marketing_name", "").lower():
            return dict(d)
    return None


def get_devices_by_brand(brand_name: str) -> List[Dict[str, Any]]:
    """Filter devices by manufacturer brand (e.g. 'Samsung', 'Xiaomi', 'OnePlus')."""
    query = brand_name.strip().lower()
    return [dict(d) for d in REAL_ANDROID_DEVICES if d["brand"].lower() == query]


def get_random_device(brand: Optional[str] = None) -> Dict[str, Any]:
    """
    Randomly selects an authentic real Android device from the 56+ device pool.
    Optionally filter by brand (e.g. 'Samsung', 'Xiaomi', 'OnePlus').
    """
    if brand:
        brand_devs = get_devices_by_brand(brand)
        if brand_devs:
            return _build_instance(random.choice(brand_devs))
    return _build_instance(random.choice(REAL_ANDROID_DEVICES))


def get_device_for_identifier(identifier: Optional[str] = None,
                              model_preference: Optional[str] = None,
                              brand_preference: Optional[str] = None,
                              random_select: bool = True) -> Dict[str, Any]:
    """
    Returns an authentic Android device profile.
    
    1. If `model_preference` is provided, selects that specific device.
    2. If `brand_preference` is provided, randomly selects among devices of that brand.
    3. If `random_select` is True (default), randomly selects from all 56 real devices.
    4. If `random_select` is False and `identifier` is provided, deterministically selects.
    """
    if model_preference:
        dev = get_device_by_model(model_preference)
        if dev:
            return _build_instance(dev, identifier)

    if brand_preference:
        brand_devices = get_devices_by_brand(brand_preference)
        if brand_devices:
            if not random_select and identifier:
                idx = int(hashlib.md5(str(identifier).encode()).hexdigest(), 16) % len(brand_devices)
                return _build_instance(brand_devices[idx], identifier)
            return _build_instance(random.choice(brand_devices), identifier)

    if not random_select and identifier:
        # Deterministic 1 ID = 1 Device system
        idx = int(hashlib.md5(str(identifier).encode()).hexdigest(), 16) % len(REAL_ANDROID_DEVICES)
        template = REAL_ANDROID_DEVICES[idx]
    else:
        # Default: randomly select from the 56 authentic real devices pool
        template = random.choice(REAL_ANDROID_DEVICES)

    return _build_instance(template, identifier)


def _build_instance(template: Dict[str, Any], identifier: Optional[str] = None) -> Dict[str, Any]:
    """Constructs a full runtime device profile instance with IDs and IPs."""
    dev = dict(template)

    if identifier:
        id_str = str(identifier).strip()
        dev["unique_device_id"] = f"Google|{uuid.uuid5(uuid.NAMESPACE_DNS, id_str)}"
        dev["android_id"] = hashlib.md5((id_str + "_aid").encode()).hexdigest()[:16]
    else:
        dev["unique_device_id"] = f"Google|{uuid.uuid4()}"
        dev["android_id"] = secrets.token_hex(8)

    dev["client_ip"] = generate_random_ip()
    return dev

